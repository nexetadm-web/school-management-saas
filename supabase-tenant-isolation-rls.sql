-- 6. Tenant Isolation Policies for online_admissions & admissions

-- online_admissions: Parents/Public can INSERT their application
DROP POLICY IF EXISTS "public_online_admissions_insert" ON public.online_admissions;
CREATE POLICY "public_online_admissions_insert"
ON public.online_admissions FOR INSERT
TO anon, authenticated
WITH CHECK (school_id IS NOT NULL);

-- online_admissions: School staff can SELECT, UPDATE, DELETE only their school's records
DROP POLICY IF EXISTS "tenant_isolation_select_online_admissions" ON public.online_admissions;
CREATE POLICY "tenant_isolation_select_online_admissions"
ON public.online_admissions FOR SELECT
TO authenticated
USING (school_id = public.get_auth_school_id());

DROP POLICY IF EXISTS "tenant_isolation_update_online_admissions" ON public.online_admissions;
