-- 3. Helper function: Get authenticated user's active school_id
CREATE OR REPLACE FUNCTION public.get_auth_school_id()
RETURNS UUID AS $$
DECLARE
    v_school_id UUID;
    v_email TEXT;
BEGIN
    -- Check profiles table
    SELECT COALESCE(current_school_id, school_id)
    INTO v_school_id
    FROM public.profiles
    WHERE id = auth.uid()
    LIMIT 1;

    IF v_school_id IS NOT NULL THEN
        RETURN v_school_id;
    END IF;

    -- Check schools by owner_id = auth.uid()
    SELECT id
    INTO v_school_id
    FROM public.schools
    WHERE owner_id::text = auth.uid()::text
    LIMIT 1;

    IF v_school_id IS NOT NULL THEN
        RETURN v_school_id;
    END IF;

    -- Check schools by owner_email = auth.jwt()->>'email'
    v_email := auth.jwt()->>'email';
    IF v_email IS NOT NULL THEN
        SELECT id
        INTO v_school_id
        FROM public.schools
        WHERE LOWER(owner_email) = LOWER(v_email)
        ORDER BY created_at ASC
        LIMIT 1;
    END IF;

    RETURN v_school_id;
END;
$$ LANGUAGE plpgsql STABLE SECURITY DEFINER;

